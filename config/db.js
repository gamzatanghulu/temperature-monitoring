const oracledb = require('oracledb');
const { SENSOR_CONFIG } = require('./sensorConfig');

oracledb.autoCommit = true;

const dbConfig = {
  user: process.env.DB_USER || "sys",
  password: process.env.DB_PASSWORD || "1234",
  connectString: process.env.DB_CONNECT_STRING || "localhost:1521/FREEPDB1",
  privilege: oracledb.SYSDBA,
  poolMin: 2,
  poolMax: 10,
  poolIncrement: 1
};

async function initDbPool() {
  await oracledb.createPool(dbConfig);
  console.log('[DB] Oracle Connection Pool 생성 완료');
}

async function createTableIfNotExists() {
  let conn;
  try {
    conn = await oracledb.getConnection();
    await conn.execute(`
      CREATE TABLE SENSOR_LOG_HISTORY (
        ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        SENSOR_NAME VARCHAR2(100) NOT NULL,
        SENSOR_TYPE VARCHAR2(50) NOT NULL,
        TEMPERATURE NUMBER(5,2),
        HUMIDITY NUMBER(5,2),
        FEELS_LIKE NUMBER(5,2),
        COLLECTED_AT TIMESTAMP DEFAULT SYSTIMESTAMP
      )
    `);
    console.log('[DB] SENSOR_LOG_HISTORY 테이블 생성 완료');
  } catch (err) {
    if (err.errorNum === 955) {
      console.log('[DB] SENSOR_LOG_HISTORY 테이블이 이미 존재합니다.');
    } else {
      console.error('[DB 오류] 테이블 생성 실패:', err.message);
    }
  } finally {
    if (conn) await conn.close();
  }
}

async function saveSensorDataToOracle(sensorItems) {
  let conn;
  try {
    conn = await oracledb.getConnection();
    const sql = `INSERT INTO sensor_log_history (sensor_name, sensor_type, temperature, humidity, feels_like, collected_at) 
                 VALUES (:name, :type, :temp, :hum, :feels, SYSTIMESTAMP)`;
    
    const binds = sensorItems.map(item => ({
      name: item.name,
      type: item.type,
      temp: item.temp,
      hum: item.hum,
      feels: item.feelsLike
    }));

    await conn.executeMany(sql, binds);
  } catch (err) {
    console.error('[DB 오류] 데이터 저장 실패:', err.message);
  } finally {
    if (conn) await conn.close();
  }
}

async function loadInitialHistoryFromOracle() {
  let conn;
  try {
    conn = await oracledb.getConnection();
    const result = await conn.execute(
      `SELECT SENSOR_NAME, TEMPERATURE, HUMIDITY, FEELS_LIKE, 
              TO_CHAR(COLLECTED_AT, 'HH24:MI:SS') AS TIME_STR 
       FROM (
         SELECT SENSOR_NAME, TEMPERATURE, HUMIDITY, FEELS_LIKE, COLLECTED_AT 
         FROM SENSOR_LOG_HISTORY 
         ORDER BY COLLECTED_AT DESC
       ) WHERE ROWNUM <= 3000`,
      {},
      { outFormat: oracledb.OUT_FORMAT_OBJECT }
    );

    if (result.rows && result.rows.length > 0) {
      const timeMap = {};
      const rawNames = Object.keys(SENSOR_CONFIG);
      const nameToIdxMap = {};

      rawNames.forEach((k, idx) => {
        nameToIdxMap[k] = idx;
        if (SENSOR_CONFIG[k].name) nameToIdxMap[SENSOR_CONFIG[k].name] = idx;
      });

      const rows = [...result.rows].reverse();

      rows.forEach(row => {
        const timeKey = row.TIME_STR;
        if (!timeMap[timeKey]) {
          timeMap[timeKey] = {
            time: timeKey,
            temps: new Array(rawNames.length).fill(null),
            hums: new Array(rawNames.length).fill(null),
            feelsLikes: new Array(rawNames.length).fill(null)
          };
        }

        const idx = nameToIdxMap[row.SENSOR_NAME];
        if (idx !== undefined && idx !== -1) {
          timeMap[timeKey].temps[idx] = row.TEMPERATURE;
          timeMap[timeKey].hums[idx] = row.HUMIDITY;
          timeMap[timeKey].feelsLikes[idx] = row.FEELS_LIKE;
        }
      });

      let history = Object.values(timeMap);
      if (history.length > 288) history = history.slice(-288);
      console.log(`[DB] 차트 이력 복원 완료: ${history.length}건`);
      return history;
    }
    return [];
  } catch (err) {
    console.error('[DB 오류] 차트 데이터 로딩 실패:', err.message);
    return [];
  } finally {
    if (conn) await conn.close();
  }
}

module.exports = {
  initDbPool,
  createTableIfNotExists,
  saveSensorDataToOracle,
  loadInitialHistoryFromOracle
};