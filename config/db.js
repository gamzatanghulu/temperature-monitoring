async function createTableIfNotExists() {
  let conn;
  try {
    conn = await oracledb.getConnection();
    
    await conn.execute(`
      CREATE TABLE SENSOR_LOG_HISTORY (
        ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        SENSOR_NAME VARCHAR2(100) NOT NULL,
        SENSOR_TYPE VARCHAR2(50) NOT NULL,
        TEMPERATURE NUMBER(10,2),
        HUMIDITY NUMBER(10,2),
        FEELS_LIKE NUMBER(10,2),
        COLLECTED_AT TIMESTAMP DEFAULT SYSTIMESTAMP
      )
    `);
    console.log('SENSOR_LOG_HISTORY 테이블이 생성되었습니다.');
  } catch (err) {
    if (err.errorNum === 955) {
      console.log('테이블이 이미 존재합니다. 컬럼 데이터 타입 변경을 시도합니다.');
      try {
        await conn.execute(`
          ALTER TABLE SENSOR_LOG_HISTORY MODIFY (
            TEMPERATURE NUMBER(10,2),
            HUMIDITY NUMBER(10,2),
            FEELS_LIKE NUMBER(10,2)
          )
        `);
        console.log('컬럼 자릿수 변경 완료 (NUMBER(10,2))');
      } catch (alterErr) {
        console.error('테이블 구조 변경 실패:', alterErr.message);
      }
    } else {
      console.error('테이블 생성 작업 실패:', err.message);
    }
  } finally {
    if (conn) await conn.close();
  }
}

async function saveSensorDataToOracle(sensorItems) {
  if (!Array.isArray(sensorItems) || sensorItems.length === 0) return;

  let conn;
  try {
    conn = await oracledb.getConnection();
    const sql = `INSERT INTO SENSOR_LOG_HISTORY (SENSOR_NAME, SENSOR_TYPE, TEMPERATURE, HUMIDITY, FEELS_LIKE, COLLECTED_AT) 
                 VALUES (:name, :type, :temp, :hum, :feels, SYSTIMESTAMP)`;
    
    const binds = sensorItems.map(item => ({
      name: item.rawName || item.name,
      type: item.type,
      temp: (item.temp !== null && item.temp !== undefined && !isNaN(item.temp)) ? Number(item.temp) : null,
      hum: (item.hum !== null && item.hum !== undefined && !isNaN(item.hum)) ? Number(item.hum) : null,
      feels: (item.feelsLike !== null && item.feelsLike !== undefined && !isNaN(item.feelsLike)) ? Number(item.feelsLike) : null
    }));

    await conn.executeMany(sql, binds);
  } catch (err) {
    console.error('센서 데이터 저장 실패:', err.message);
  } finally {
    if (conn) await conn.close();
  }
}

async function loadInitialHistoryFromOracle() {
  let conn;
  try {
    conn = await oracledb.getConnection();
    const result = await conn.execute(
      `SELECT SENSOR_NAME, TEMPERATURE, HUMIDITY, FEELS_LIKE, 
              TO_CHAR(COLLECTED_AT, 'HH24:MI:SS') AS TIME_STR 
       FROM (
         SELECT SENSOR_NAME, TEMPERATURE, HUMIDITY, FEELS_LIKE, COLLECTED_AT 
         FROM SENSOR_LOG_HISTORY 
         ORDER BY COLLECTED_AT DESC
       ) WHERE ROWNUM <= 3000`,
      {},
      { outFormat: oracledb.OUT_FORMAT_OBJECT }
    );

    if (result.rows && result.rows.length > 0) {
      const timeMap = {};
      const rawNames = Object.keys(SENSOR_CONFIG);
      const nameToIdxMap = {};

      rawNames.forEach((k, idx) => {
        nameToIdxMap[k] = idx;
        if (SENSOR_CONFIG[k].name) nameToIdxMap[SENSOR_CONFIG[k].name] = idx;
      });

      const rows = [...result.rows].reverse();

      rows.forEach(row => {
        const timeKey = row.TIME_STR;
        if (!timeMap[timeKey]) {
          timeMap[timeKey] = {
            time: timeKey,
            temps: new Array(rawNames.length).fill(null),
            hums: new Array(rawNames.length).fill(null),
            feelsLikes: new Array(rawNames.length).fill(null)
          };
        }

        const idx = nameToIdxMap[row.SENSOR_NAME];
        if (idx !== undefined && idx !== -1) {
          timeMap[timeKey].temps[idx] = row.TEMPERATURE;
          timeMap[timeKey].hums[idx] = row.HUMIDITY;
          timeMap[timeKey].feelsLikes[idx] = row.FEELS_LIKE;
        }
      });

      let history = Object.values(timeMap);
      if (history.length > 288) history = history.slice(-288);
      console.log(`차트 초기 이력 복원 완료: ${history.length}건`);
      return history;
    }
    return [];
  } catch (err) {
    console.error('차트 데이터 로딩 실패:', err.message);
    return [];
  } finally {
    if (conn) await conn.close();
  }
}

// 💡 [추가된 기능] 현재 DB 용량 및 SENSOR_LOG_HISTORY 테이블 크기 조회 함수
async function checkDatabaseStorage() {
  let conn;
  try {
    conn = await oracledb.getConnection();
    
    // 1. SENSOR_LOG_HISTORY 테이블 실제 크기 조회
    const tableResult = await conn.execute(
      `SELECT 
         NVL(SUM(bytes)/1024/1024, 0) AS TABLE_MB 
       FROM user_segments 
       WHERE segment_name = 'SENSOR_LOG_HISTORY'`,
      {},
      { outFormat: oracledb.OUT_FORMAT_OBJECT }
    );
    
    const tableSizeMb = tableResult.rows[0]?.TABLE_MB || 0;

    console.log('========================================');
    console.log(`📊 [오라클 DB 용량 모니터링]`);
    console.log(`- SENSOR_LOG_HISTORY 테이블 크기: ${Number(tableSizeMb).toFixed(2)} MB`);
    console.log(`- 오라클 Always Free 제공 무료 한도: 20,000 MB (20 GB)`);
    console.log(`- 남은 예상 용량 공간: 약 ${(20000 - tableSizeMb).toFixed(2)} MB 여유`);
    console.log('========================================');

  } catch (err) {
    console.error('DB 용량 조회 중 오류 발생 (권한 등):', err.message);
  } finally {
    if (conn) await conn.close();
  }
}

